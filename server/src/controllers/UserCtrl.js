import { GraphQLError } from 'graphql';
import pool from './db.js';

const EMAIL_PATTERN = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
const UUID_PATTERN =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

function badInput(message, field) {
  return new GraphQLError(message, {
    extensions: { code: 'BAD_USER_INPUT', field },
  });
}

// Maps a `user` row (snake_case) to the GraphQL User shape (camelCase).
function toUser(row) {
  return {
    uuid: row.uuid,
    firstName: row.first_name,
    lastName: row.last_name,
    email: row.email,
    status: row.status,
  };
}

export default class UserCtrl {
  /**
   * Creates a user. The `uuid` is generated by the client; `status` comes
   * from the table default.
   * @returns {Promise<{uuid, firstName, lastName, email, status}>}
   */
  static async register({ uuid, firstName, lastName, email }) {
    const values = {
      uuid: String(uuid ?? '').trim().toLowerCase(),
      firstName: String(firstName ?? '').trim(),
      lastName: String(lastName ?? '').trim(),
      email: String(email ?? '').trim().toLowerCase(),
    };

    if (!UUID_PATTERN.test(values.uuid)) {
      throw badInput('A valid UUID is required.', 'uuid');
    }
    if (!values.firstName) throw badInput('First name is required.', 'firstName');
    if (values.firstName.length > 100) {
      throw badInput('First name must be 100 characters or less.', 'firstName');
    }
    if (!values.lastName) throw badInput('Last name is required.', 'lastName');
    if (values.lastName.length > 100) {
      throw badInput('Last name must be 100 characters or less.', 'lastName');
    }
    if (!values.email) throw badInput('Email is required.', 'email');
    if (values.email.length > 255 || !EMAIL_PATTERN.test(values.email)) {
      throw badInput('Enter a valid email address.', 'email');
    }

    try {
      const [result] = await pool.query(
        'INSERT INTO `user` (`uuid`, `first_name`, `last_name`, `email`) VALUES (?, ?, ?, ?)',
        [values.uuid, values.firstName, values.lastName, values.email],
      );
      const [rows] = await pool.query(
        'SELECT `uuid`, `first_name`, `last_name`, `email`, `status` FROM `user` WHERE `id` = ?',
        [result.insertId],
      );
      return toUser(rows[0]);
    } catch (error) {
      // The unique index name in the message tells which column clashed.
      // e.g. "Duplicate entry '…' for key 'user.uuid'"
      if (
        error.code === 'ER_DUP_ENTRY' &&
        /for key '(?:\w+\.)?uuid'$/.test(error.sqlMessage)
      ) {
        throw new GraphQLError('This UUID is already in use.', {
          extensions: { code: 'UUID_TAKEN', field: 'uuid' },
        });
      }
      if (error.code === 'ER_DUP_ENTRY') {
        throw new GraphQLError('Email is already registered.', {
          extensions: { code: 'EMAIL_TAKEN', field: 'email' },
        });
      }
      console.error('UserCtrl.register failed:', error);
      throw new GraphQLError('Could not register the user.', {
        extensions: { code: 'INTERNAL_SERVER_ERROR' },
      });
    }
  }
}
