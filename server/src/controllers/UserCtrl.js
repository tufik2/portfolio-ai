import { GraphQLError } from 'graphql';
import pool from './db.js';
import EmailCtrl from './EmailCtrl.js';
import UtilsCtrl from './UtilsCtrl.js';

const USER_COLUMNS = '`uuid`, `first_name`, `last_name`, `email`, `status`';

function badInput(message, field) {
	return new GraphQLError(message, {
		extensions: { code: 'BAD_USER_INPUT', field },
	});
}

// Maps a `user` row (snake_case) to the GraphQL User shape (camelCase).
function toUser(row) {
	return {
		uuid: row.uuid,
		firstName: row.first_name,
		lastName: row.last_name,
		email: row.email,
		status: row.status,
	};
}

// Sends the verification email in the background: a failed email is logged
// but never fails the request that triggered it.
function sendVerificationEmail(user, token) {
	Promise.resolve()
	.then(() => EmailCtrl.sendRegistration(user, UtilsCtrl.verifyEmailUrl(token)))
	.catch((emailError) => {
		console.error(
			`Verification email to ${user.email} failed:`,
			emailError.message,
		);
	});
}

// Minimum time between two resends to the same address (in-memory, so it
// resets when the server restarts).
const RESEND_COOLDOWN_MS = 60 * 1000;
const lastResendAt = new Map();

export default class UserCtrl {
	/**
	 * Creates a user with status EMAIL_VERIFICATION (table default) and emails
	 * them a one-time link to verify their address. The `uuid` is generated by
	 * the client; the verification token is generated here, and only its hash
	 * is saved.
	 * @returns {Promise<{uuid, firstName, lastName, email, status}>}
	 */
	static async register({ uuid, firstName, lastName, email }) {
		const values = {
			uuid: String(uuid ?? '').trim().toLowerCase(),
			firstName: String(firstName ?? '').trim(),
			lastName: String(lastName ?? '').trim(),
			email: String(email ?? '').trim().toLowerCase(),
		};
		
		if (!UtilsCtrl.isUUID(values.uuid)) {
			throw badInput('A valid UUID is required.', 'uuid');
		}
		if (!values.firstName) throw badInput('First name is required.', 'firstName');
		if (values.firstName.length > 100) {
			throw badInput('First name must be 100 characters or less.', 'firstName');
		}
		if (!values.lastName) throw badInput('Last name is required.', 'lastName');
		if (values.lastName.length > 100) {
			throw badInput('Last name must be 100 characters or less.', 'lastName');
		}
		if (!values.email) throw badInput('Email is required.', 'email');
		if (values.email.length > 255 || !UtilsCtrl.isEmail(values.email)) {
			throw badInput('Enter a valid email address.', 'email');
		}
		
		const token = UtilsCtrl.newVerificationToken();
		
		try {
			const [result] = await pool.query(
				`INSERT INTO \`user\`
				 (\`uuid\`, \`first_name\`, \`last_name\`, \`email\`, \`email_verification_hash\`)
				 VALUES (?, ?, ?, ?, ?)`,
				[
					values.uuid,
					values.firstName,
					values.lastName,
					values.email,
					UtilsCtrl.hashToken(token),
				],
			);
			const [rows] = await pool.query(
				`SELECT ${USER_COLUMNS} FROM \`user\` WHERE \`id\` = ?`,
				[result.insertId],
			);
			const user = toUser(rows[0]);
			sendVerificationEmail(user, token);
			return user;
		} catch (error) {
			// The unique index name in the message tells which column clashed.
			// e.g. "Duplicate entry '…' for key 'user.uuid'"
			if (
				error.code === 'ER_DUP_ENTRY' &&
				/for key '(?:\w+\.)?uuid'$/.test(error.sqlMessage)
			) {
				throw new GraphQLError('This UUID is already in use.', {
					extensions: { code: 'UUID_TAKEN', field: 'uuid' },
				});
			}
			if (error.code === 'ER_DUP_ENTRY') {
				throw new GraphQLError('Email is already registered.', {
					extensions: { code: 'EMAIL_TAKEN', field: 'email' },
				});
			}
			console.error('UserCtrl.register failed:', error);
			throw new GraphQLError('Could not register the user.', {
				extensions: { code: 'INTERNAL_SERVER_ERROR' },
			});
		}
	}
	
	/**
	 * Sends a new verification link to a user still in EMAIL_VERIFICATION.
	 * The new token replaces the old one, so earlier links stop working.
	 * Always resolves to true, whether or not the email belongs to a pending
	 * user, so the response can't be used to find out which emails exist.
	 * @returns {Promise<true>}
	 */
	static async resendVerificationEmail(email) {
		const address = String(email ?? '').trim().toLowerCase();
		if (!address || address.length > 255 || !UtilsCtrl.isEmail(address)) {
			throw badInput('Enter a valid email address.', 'email');
		}
		
		const last = lastResendAt.get(address) ?? 0;
		if (Date.now() - last < RESEND_COOLDOWN_MS) return true;
		lastResendAt.set(address, Date.now());
		
		const token = UtilsCtrl.newVerificationToken();
		try {
			const [result] = await pool.query(
				"UPDATE `user` SET `email_verification_hash` = ? WHERE `email` = ? AND `status` = 'EMAIL_VERIFICATION'",
				[UtilsCtrl.hashToken(token), address],
			);
			if (result.affectedRows === 0) return true;
			
			const [rows] = await pool.query(
				`SELECT ${USER_COLUMNS} FROM \`user\` WHERE \`email\` = ?`,
				[address],
			);
			sendVerificationEmail(toUser(rows[0]), token);
			return true;
		} catch (error) {
			console.error('UserCtrl.resendVerificationEmail failed:', error);
			throw new GraphQLError('Could not resend the email.', {
				extensions: { code: 'INTERNAL_SERVER_ERROR' },
			});
		}
	}
	
	/**
	 * Consumes a one-time verification token: sets the user to ACTIVE, saves
	 * the verification date and clears the token so the link can't be used
	 * again. Tokens never expire.
	 * @returns {Promise<{uuid, firstName, lastName, email, status}>}
	 */
	static async verifyEmail(token) {
		const invalid = () =>
			new GraphQLError(
				'This verification link is invalid or has already been used.',
				{ extensions: { code: 'INVALID_TOKEN' } },
			);
		
		const value = String(token ?? '').trim();
		if (!value) throw invalid();
		const hash = UtilsCtrl.hashToken(value);
		
		const [rows] = await pool.query(
			'SELECT `id`, `status` FROM `user` WHERE `email_verification_hash` = ?',
			[hash],
		);
		if (rows.length === 0) throw invalid();
		if (rows[0].status === 'INACTIVE') {
			// A deactivated account is not re-activated by the link.
			throw new GraphQLError('This account can no longer be verified.', {
				extensions: { code: 'ACCOUNT_INACTIVE' },
			});
		}
		
		// Conditional on the hash still matching, so two simultaneous requests
		// with the same link can't both succeed.
		const [result] = await pool.query(
			`UPDATE \`user\`
			 SET \`status\` = 'ACTIVE',
			     \`email_verified_at\` = UTC_TIMESTAMP(),
			     \`email_verification_hash\` = NULL
			 WHERE \`id\` = ? AND \`email_verification_hash\` = ?`,
			[rows[0].id, hash],
		);
		if (result.affectedRows === 0) throw invalid();
		
		const [users] = await pool.query(
			`SELECT ${USER_COLUMNS} FROM \`user\` WHERE \`id\` = ?`,
			[rows[0].id],
		);
		return toUser(users[0]);
	}
}
